WITH
PR AS (
SELECT
   PRODUCT_ID,
   ROUND(SUM(REVENUE)::NUMERIC, 2) AS REVENUE
FROM
   FACT_ORDERS
 GROUP BY PRODUCT_ID
   ORDER BY PRODUCT_ID
	)
SELECT
	PRODUCT_ID,
	REVENUE,
	ROUND(REVENUE / SUM(REVENUE) OVER () * 100, 2) AS REVENUE_PCT
FROM
	PR
ORDER BY REVENUE DESC
LIMIT 20