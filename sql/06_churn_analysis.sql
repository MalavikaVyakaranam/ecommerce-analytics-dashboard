WITH LP AS (SELECT CUSTOMER_ID, MAX(INVOICE_DATE) AS LAST_ORDER FROM FACT_ORDERS GROUP BY CUSTOMER_ID)
SELECT CUSTOMER_ID, LAST_ORDER, ('2012-01-01' :: DATE - LAST_ORDER) AS DAYS_INACTIVE,
CASE 
WHEN ('2012-01-01' :: DATE - LAST_ORDER) > 180 THEN 'CHURNED'
WHEN ('2012-01-01' :: DATE - LAST_ORDER) > 90  THEN 'AT RISK'
ELSE 'ACTIVE'
END AS CHURN_STATUS 
FROM LP
ORDER BY DAYS_INACTIVE DESC


