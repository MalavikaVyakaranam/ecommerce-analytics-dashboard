WITH COHORTS AS (SELECT CUSTOMER_ID, DATE_TRUNC ('MONTH', MIN(INVOICE_DATE)) AS COHORT_MONTH FROM FACT_ORDERS GROUP BY 1),
ACTIVITY AS (SELECT DISTINCT CUSTOMER_ID, DATE_TRUNC ('MONTH', INVOICE_DATE) AS ACTIVE_MONTH FROM FACT_ORDERS)
SELECT C.COHORT_MONTH,
COUNT (DISTINCT C. CUSTOMER_ID) AS COHORT_SIZE,
COUNT (DISTINCT A.CUSTOMER_ID) AS RETURNED,
ROUND(COUNT (DISTINCT A.CUSTOMER_ID) * 100.0 / COUNT (DISTINCT C.CUSTOMER_ID),2) AS RETENTION_PCT FROM COHORTS C  LEFT JOIN ACTIVITY A
ON C.CUSTOMER_ID = A.CUSTOMER_ID
AND A.ACTIVE_MONTH=C.COHORT_MONTH + INTERVAL '1 MONTH' GROUP BY 1 ORDER BY 1

